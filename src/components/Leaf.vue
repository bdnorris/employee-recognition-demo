<script>
import { computed, ref } from "vue";
import { onMounted } from "vue";

import gsap from "gsap";

export default {
	props: {
		trait: {
			type: String,
			default: "",
		},
		direction: {
			type: String,
			default: "left",
		},
		index: {
			type: Number,
			default: 0,
		},
		isSelected: {
			type: Boolean,
			default: false,
		},
	},
	setup(props, context) {
		const leaf = ref(null);

		const origin = computed({
			get() {
				return props.direction === "right" ? "bottom left" : "bottom right";
			},
		});

		onMounted(() => {
			// console.log("leaf", leaf.value);
			gsap.to(leaf.value, {
				duration: "random(0.5, 1, 0.1)",
				delay: "random(0.1, 0.4, 0.1)",
				repeat: -1,
				yoyo: true,
				rotate: 12,
				transformOrigin: origin.value,
			});
		});

		const leafSelect = (e) => {
			// console.log("leafSelect", e, props.index, props.isSelected);
			context.emit("leafSelect", e, props.index);
		};

		const color = computed({
			get() {
				switch (props.trait) {
					case "passionate":
						return "orange";
					case "authentic":
						return "red";
					case "inspiring":
						return "blue";
					case "courageous":
						return "green";
					case "relentless":
						return "dgreen";
					case "reliable":
						return "burgundy";
					default:
						return "";
				}
			},
		});

		const borderColor = computed({
			get() {
				switch (props.trait) {
					case "passionate":
						return "#A36B2E";
					case "authentic":
						return "#8D2A03";
					case "inspiring":
						return "#1b6967";
					case "courageous":
						return "#5B7918";
					case "relentless":
						return "#14341E";
					case "reliable":
						return "#572B3A";
					default:
						return "";
				}
			},
		});

		return { color, borderColor, leafSelect, origin, leaf, ...props };
	},
};
